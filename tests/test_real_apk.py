"""Opt-in integration checks using the exact user APK already placed in apk-inspection.

Skip gracefully if files aren't present. This verifies generated bytecode, not
Pairip license, UI rendering, app startup, or signed-package installability.
"""
from pathlib import Path
import hashlib
import json
import os
import subprocess
import unittest
import zipfile

ROOT = Path(__file__).resolve().parents[1]
APK_DIR = ROOT / "apk-inspection"
SOURCE = APK_DIR / "hatena-bookmark-v5.84-58400.apk"
PATCHED = APK_DIR / "HatenaBookmark-5.84-PR-hidden-clone-test.apk"
REPORT = APK_DIR / "hatena-patch-test.json"
DEXDUMP = Path(os.getenv(
    "ANDROID_DEXDUMP", r"C:\Users\kkoji\AppData\Local\Android\Sdk\build-tools\36.0.0\dexdump.exe"
))

@unittest.skipUnless(
    SOURCE.is_file() and PATCHED.is_file() and REPORT.is_file(),
    "Real APK input and output not present in this environment",
)
class RealApkTests(unittest.TestCase):
    def test_exact_source_and_report(self):
        digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
        self.assertEqual(
            digest, "0e2c6727e92a8a4ecbb05a4fdcd9059d80c11552ff6f4155d94c874247384684"
        )
        result = json.loads(REPORT.read_text(encoding="utf-8"))
        self.assertEqual(result.get("packageName"), "com.hatena.android.bookmark")
        self.assertEqual(result.get("packageVersion"), "5.84")
        self.assertEqual(result["failedPatches"], [])
        self.assertEqual(
            {p["name"] for p in result["appliedPatches"]},
            {"Hide native PR entries from article feeds", "Clone Hatena Bookmark for safe side-by-side testing"},
        )
        self.assertTrue(all(step["success"] for step in result["patchingSteps"]))

    def test_modified_class_was_added(self):
        with zipfile.ZipFile(SOURCE) as original, zipfile.ZipFile(PATCHED) as output:
            self.assertIsNone(output.testzip())
            self.assertEqual(original.read("classes2.dex"), output.read("classes2.dex"))
            self.assertIn("classes3.dex", output.namelist())
            dex = output.read("classes3.dex")
            self.assertTrue(dex.startswith(b"dex" + bytes([10])))
            self.assertIn(b"MuteHelperKt", dex)
            self.assertIn(b"filteredWithMuteWords", dex)
            self.assertIn(b"isPrEntry", dex)

    @unittest.skipUnless(DEXDUMP.is_file(), "Android SDK dexdump unavailable")
    def test_executable_pr_guard_at_method_entry(self):
        with zipfile.ZipFile(PATCHED) as output:
            dex = output.read("classes3.dex")
        path = APK_DIR / "classes3-patch-verify.dex"
        path.write_bytes(dex)
        result = subprocess.run(
            [str(DEXDUMP), "-d", str(path)],
            capture_output=True, text=True, check=True,
        )
        raw = result.stdout
        method = raw.split("name          : 'filteredWithMuteWords'")[-1]
        method = method.split("catches       :")[0]
        code = [line for line in method.splitlines() if "|000" in line][:10]
        self.assertGreaterEqual(len(code), 8, "\n".join(code))
        self.assertIn("isPrEntry", code[0])
        self.assertIn("move-result v0", code[1])
        self.assertIn("if-eqz v0", code[2])
        self.assertIn("const/4 v0, #int 0", code[3])
        self.assertIn("return v0", code[4])
        self.assertIn("getTitle", code[6])

if __name__ == "__main__":
    unittest.main()
